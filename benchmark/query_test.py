CH_STOPWORDS = {
    "的", "了", "在", "是", "和", "与", "及", "或", "以及", "一个", "一次", "对于", "这种",
    "中", "中间", "相关", "进行", "主要", "主要是", "包括", "其中", "等", "共计", "还有", "有关",
    "问题", "回答", "问题是", "答案", "生成", "模型", "如果", "但", "但是", "并且", "以及",
}
EN_STOPWORDS = {
    "the", "a", "an", "and", "or", "to", "of", "in", "on", "with", "for", "by", "at",
    "from", "as", "that", "this", "these", "those", "is", "are", "was", "were", "be", "been",
    "it", "its", "their", "there", "here", "into", "over", "under", "about", "without",
}


def extract_entities(text: str) -> Dict[str, set]:
    ips = set(re.findall(r"\b(?:\d{1,3}\.){3}\d{1,3}\b", text))
    cves = set(re.findall(r"CVE-\d{4}-\d+", text, flags=re.IGNORECASE))
    nums = set(re.findall(r"\b\d{2,}\b", text))
    upper_terms = set([t for t in re.findall(
        r"\b[A-Z][A-Z0-9_\-]{2,}\b", text) if not t.startswith("CVE-")])
    return {"ip": ips, "cve": cves, "num": nums, "upper": upper_terms}


def normalize(text: str) -> str:
    text = re.sub(r"[^0-9A-Za-z\u4e00-\u9fff._\-]", " ", text)
    return text.lower()


def tokenize(text: str) -> set:
    text = normalize(text)
    tokens = [t for t in text.split() if t]
    filtered = set(
        t for t in tokens
        if t not in EN_STOPWORDS and t not in CH_STOPWORDS and len(t) > 1
    )
    return filtered


def coverage_score(ground: str, generated: str) -> Tuple[float, Dict[str, Any]]:
    gt_tokens = tokenize(ground)
    gen_tokens = tokenize(generated)

    token_cov = (len(gt_tokens & gen_tokens) /
                 max(1, len(gt_tokens))) if gt_tokens else 0.0

    gt_entities = extract_entities(ground)
    gen_entities = extract_entities(generated)

    entity_scores = {}
    weights = {"ip": 0.4, "cve": 0.3, "num": 0.15, "upper": 0.15}
    ent_cov_total = 0.0
    for k, w in weights.items():
        gt_set = gt_entities.get(k, set())
        if not gt_set:
            s = 1.0
        else:
            inter = gt_set & gen_entities.get(k, set())
            s = len(inter) / max(1, len(gt_set))
        entity_scores[k] = s
        ent_cov_total += w * s

    score = 0.7 * token_cov + 0.3 * ent_cov_total
    details = {
        "token_coverage": round(token_cov, 4),
        "entity_coverage": {k: round(v, 4) for k, v in entity_scores.items()},
        "composite_score": round(score, 4),
    }
    return score, details


def evaluate_answer(original_query: str, ground_truth: str, generated: str) -> Dict[str, str]:
    score, details = coverage_score(ground_truth, generated)
    threshold = 0.8
    relevant = score >= threshold
    
    analysis = (
        f"Token Coverage: {int(details['token_coverage']*100)}%, "
        f"Weighted Entity Coverage: {int((details['entity_coverage']['ip']*0.4 + details['entity_coverage']['cve']*0.3 + details['entity_coverage']['num']*0.15 + details['entity_coverage']['upper']*0.15)*100)}%, "
        f"Composite Score: {int(details['composite_score']*100)}%. "
        + ("Key information coverage is sufficient; judged as Relevant." if relevant else "Core information coverage is insufficient; judged as Irrelevant.")
    )
    return {"analysis_process": analysis, "judgment_result": "Relevant" if relevant else "Irrelevant"}


def build_llm_prompt(original_query: str, ground_truth: str, generated: str) -> list:
    instruction = (
        "# Role\n"
        "You are a senior AI QA system evaluation expert. Your task is to accurately and objectively evaluate whether the AI-generated answer is highly relevant to the Ground Truth.\n\n"
        "# Core Task\n"
        "You need to compare the semantic relevance between a 'Generated Answer' and a 'Standard Answer'. Based on the following quantitative criteria, you must give a final judgment: if the 'Generated Answer' contains more than 80% of the core information in the 'Standard Answer', judge it as 'Relevant', otherwise judge it as 'Irrelevant'.\n\n"
        "# Input\n"
        "For each evaluation, you will receive three parts:\n\n"
        "Original Query: The context in which the question was asked.\n\n"
        "Ground Truth Answer: The reference answer considered completely correct and standard.\n\n"
        "Generated Answer: The answer generated by the AI model that needs evaluation.\n\n"
        "# Evaluation Criteria: How to define '80% Relevance'\n\n"
        "This is a semantic judgment about information coverage, not simple keyword matching. Please follow these guidelines:\n\n"
        "Cases to be judged as 'Relevant' (Relevance > 80%):\n\n"
        "Core Information Match: The 'Generated Answer' must accurately contain all key entities, facts, and conclusions from the 'Standard Answer'.\n\n"
        "Minor Information Omission Allowed: The 'Generated Answer' can omit some supplementary descriptions, examples, or less important details from the 'Standard Answer'.\n\n"
        "Different Phrasing Allowed: The 'Generated Answer' does not need to use the exact same wording as the 'Standard Answer', as long as it remains semantically consistent.\n\n"
        "No Major Factual Errors: The 'Generated Answer' must not contain serious factual errors (hallucinations) that contradict the 'Standard Answer'.\n\n"
        "Cases to be judged as 'Irrelevant' (Relevance < 80%):\n\n"
        "Core Information Missing: The 'Generated Answer' omits key arguments or main facts from the 'Standard Answer'.\n\n"
        "Factual Contradiction: The 'Generated Answer' contains incorrect information that directly conflicts with the 'Standard Answer'.\n\n"
        "Answering the Wrong Question: The 'Generated Answer', though possibly correct in content, does not address the 'Original Query' and deviates from the topic.\n\n"
        "Too Vague or Non-Informative: The 'Generated Answer' is too general and provides no valuable specific information.\n\n"
        "# Workflow\n\n"
        "1. Read the Original Query carefully to understand the intent.\n"
        "2. Read the Standard Answer carefully to grasp all core points that should be included.\n"
        "3. Read the Generated Answer carefully.\n"
        "4. Compare the Generated Answer and Standard Answer based on the '80% Relevance' criteria.\n"
        "5. Brief analysis of your judgment logic.\n"
        "6. Provide your final judgment according to the specified output format.\n\n"
        "# Output Format\n"
        "Your output must contain exactly two parts:\n\n"
        "Analysis Process: [Briefly explain your judgment logic in one or two sentences. Example: The generated answer accurately identified the core attack method and IP address, only missing specific port info, satisfying the >80% relevance standard.]\n"
        "Judgment Result: [Relevant/Irrelevant]\n\n"
        "# Examples\n\n"
        "Example 1:\n\n"
        "Original Query: In the key attacks on January 6th, what was the main attack method of IP 47.116.13.239?\n\n"
        "Standard Answer: This IP mainly utilized multiple Web vulnerabilities, including Nkon security gateway file reading and MetInfo SQL injection. Its most common payload is 'file reading', totaling 657 times. Additionally, it is associated with 'Colorful Snake hacker tool' and 'VIPER' red team system.\n\n"
        "Generated Answer: IP 47.116.13.239 primarily attacked by exploiting Web vulnerabilities, especially file reading and SQL injection.\n\n"
        "Your Output:\n\n"
        "Analysis Process: The generated answer accurately identified the core attack methods 'Web vulnerabilities', 'file reading', and 'SQL injection', covering the main information points of the standard answer. Although it omitted minor details like tool names, core relevance exceeds 80%.\n"
        "Judgment Result: Relevant\n\n"
        "Example 2:\n\n"
        "Original Query: Which historical IP has the most attacks? Where is it from?\n\n"
        "Standard Answer: The historical IP with the most attacks is 107.172.21.17, with 28,834 attacks. This IP is from the United States.\n\n"
        "Generated Answer: The IP with the most attacks conducted a large number of scanning activities, which usually come from overseas.\n\n"
        "Your Output:\n\n"
        "Analysis Process: The generated answer mentioned 'scanning' and 'from overseas' but completely missed the most core IP address '107.172.21.17' and the specific origin 'United States'. Core information is missing, relevance is far below 80%.\n"
        "Judgment Result: Irrelevant\n"
    )
    user_msg = (
        f"Original Query:\n{original_query}\n\n"
        f"Standard Answer:\n{ground_truth}\n\n"
        f"Generated Answer:\n{generated}\n\n"
        "Please strictly follow the specified output format and output only two lines."
    )
    return [
        {"role": "system", "content": instruction},
        {"role": "user", "content": user_msg},
    ]


def evaluate_with_llm(original: str, ground: str, generated: str,
                      model_provider: str = None, model_name: str = None) -> dict:
    from packages.models import select_model
    model = select_model(model_provider=model_provider, model_name=model_name)
    messages = build_llm_prompt(original, ground, generated)
    resp = model.predict(messages)
    text = resp.content.strip()
    lines = [l.strip() for l in text.splitlines() if l.strip()]
    if len(lines) >= 2:
        return {"analysis_process": lines[0].replace("Analysis Process:", "").strip(),
                "judgment_result": lines[1].replace("Judgment Result:", "").strip()}
    return {"analysis_process": text, "judgment_result": "Irrelevant"}


def call_chat_stream(query: str, server: str, db_id: str) -> str:
    url = server.rstrip("/") + "/chat/stream"
    payload = {
        "query": query,
        "meta": {"db_id": db_id, "show_retrieval_info": True},
        "history": []
    }
    headers = {"Content-Type": "application/json"}
    resp = requests.post(url, data=json.dumps(
        payload), headers=headers, stream=True, timeout=120)
    resp.raise_for_status()
    answer = []
    for line in resp.iter_lines(decode_unicode=True):
        if not line:
            continue
        try:
            obj = json.loads(line)
        except Exception:
            continue
        if obj.get("status") == "loading" and obj.get("response"):
            answer.append(obj["response"])
        elif obj.get("status") == "finished":
            break
    return "".join(answer).strip()


def main():
    """CLI Usage:
    1) Rule-based evaluation (local):
       python benchmark/query_test.py "<query>" "<ground_truth>" "<generated>"
    2) LLM evaluation:
       MODEL_PROVIDER=custom MODEL_NAME=gemini-1.5-pro \
       python benchmark/query_test.py --llm "<query>" "<ground_truth>" "<generated>"
    3) Batch evaluation (reads Excel and calls backend /chat/stream):
       python benchmark/query_test.py --batch --llm \
         --server http://localhost:8000 \
         --db kb_ffe24eeb \
         --dataset benchmark/dataset.xlsx \
         --out benchmark/result.csv
    """
    use_llm = False
    args = sys.argv[1:]
    
    if "--llm" in args:
        use_llm = True
        args = [a for a in args if a != "--llm"]

    if "--batch" in args:
        args = [a for a in args if a != "--batch"]

        # Default parameters
        server = "http://localhost:8000"
        db_id = "kb_ffe24eeb"
        dataset_path = "benchmark/dataset.xlsx"
        out_path = None

        i = 0
        while i < len(args):
            if args[i] == "--server" and i + 1 < len(args):
                server = args[i+1]
                i += 2
                continue
            if args[i] == "--db" and i + 1 < len(args):
                db_id = args[i+1]
                i += 2
                continue
            if args[i] == "--dataset" and i + 1 < len(args):
                dataset_path = args[i+1]
                i += 2
                continue
            if args[i] == "--out" and i + 1 < len(args):
                out_path = args[i+1]
                i += 2
                continue
            i += 1

        print(f"Starting batch evaluation using dataset: {dataset_path}")
        df = pd.read_excel(dataset_path)
        query_col = next((c for c in df.columns if c.lower().strip() in ("query", "question")), None)
        answer_col = next((c for c in df.columns if c.lower().strip() in ("answer", "ground truth", "ground_truth")), None)
        
        if not query_col or not answer_col:
            print("Error: Dataset must contain 'Query' and 'Answer' (or 'Ground Truth') columns.")
            return

        results = []
        correct = 0
        total = 0
        provider = os.getenv("MODEL_PROVIDER") or None
        name = os.getenv("MODEL_NAME") or None
        start_time = time.time()

        for idx, row in df.iterrows():
            q = str(row[query_col]).strip()
            gt = str(row[answer_col]).strip()
            if not q or not gt:
                continue
            try:
                pred = call_chat_stream(q, server, db_id)
            except Exception as e:
                pred = f"<Call Failed: {e}>"
            
            judge = evaluate_with_llm(q, gt, pred, provider, name) if use_llm else evaluate_answer(q, gt, pred)
            
            is_rel = 1 if judge.get("judgment_result") == "Relevant" else 0
            correct += is_rel
            total += 1
            results.append({
                "id": idx + 1,
                "query": q,
                "pred": pred,
                "gt": gt,
                "judge": judge.get("judgment_result"),
                "analysis": judge.get("analysis_process"),
                "is_correct": is_rel,
            })
            print(f"[{total}] Processed: {q[:50]}... | Result: {judge.get('judgment_result')}")

        accuracy = (correct / total) if total else 0.0
        elapsed = time.time() - start_time
        print("\nBatch Evaluation Complete:")
        print(f"Total Samples: {total}, Accuracy: {accuracy:.2%}, Time: {elapsed:.1f}s")
        
        out_df = pd.DataFrame(results)
        if out_path:
            out_df.to_csv(out_path, index=False)
            print(f"Detailed results saved to: {out_path}")
        else:
            print("\nFirst 10 results:")
            print(out_df[["id", "judge", "is_correct"]].head(10).to_string(index=False))
        return

    if len(args) >= 3:
        original, ground, generated = args[0], args[1], args[2]
        provider = os.getenv("MODEL_PROVIDER") or None
        name = os.getenv("MODEL_NAME") or None
        res = evaluate_with_llm(original, ground, generated, provider, name) if use_llm else evaluate_answer(original, ground, generated)
        print(f"Analysis Process: {res['analysis_process']}")
        print(f"Judgment Result: {res['judgment_result']}")
    else:
        # Example run
        print("Usage: python benchmark/query_test.py <query> <ground_truth> <generated>")
        print("Example evaluation:")
        q = "What is the primary target of this attack?"
        gt = "The primary target is the internal database server at IP 10.0.0.5."
        pred = "The attack targets the database server (10.0.0.5)."
        res = evaluate_answer(q, gt, pred)
        print(f"Query: {q}")
        print(f"Analysis: {res['analysis_process']}")
        print(f"Result: {res['judgment_result']}")


if __name__ == "__main__":
    main()
